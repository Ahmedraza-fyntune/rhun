#!/usr/bin/env python3
"""Generates src/gfx/icondata.s: icon drawing programs on a 128x128 grid (16 px = 128 units).
Ops: W w | M x y | L x y | O cx cy r (ring) | D cx cy r (disc) | P n x y ... (filled polygon)
F n x y ... preserves SVG contour winding, including holes."""
import json, math, os

def arc(cx, cy, r, a0, a1, n):
    return [(round(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n))),
             round(cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n)))) for i in range(n + 1)]

def line(pts):
    return [('M',) + pts[0]] + [('L',) + p for p in pts[1:]]

box = [(12, 20), (116, 20), (116, 108), (12, 108), (12, 20)]
