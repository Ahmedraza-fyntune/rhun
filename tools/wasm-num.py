def h(name, body, doc=None):
    if doc: w('# '+doc)
    w('h_%s:' % name)
    for l in body.strip('\n').split('\n'):
        l=l.strip()
        if not l: continue
        if l.endswith(':') or (l[0].isdigit() and ':' in l[:3]):
            w(l if not l[0].isdigit() else l)
        else:
            w('    '+l)
    w('    NEXT')

def bin32(name, op):
    h(name, '''mov eax, [r12 - 16]
%s
mov [r12 - 16], rax
sub r12, 8''' % op)
def bin64(name, op):
    h(name, '''mov rax, [r12 - 16]
%s
mov [r12 - 16], rax
sub r12, 8''' % op)

