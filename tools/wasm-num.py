def fl(bits):
    s = 'ss' if bits==32 else 'sd'
    t = 'f32' if bits==32 else 'f64'
    ld = (lambda x,m: 'movd %s, dword ptr %s' % (x,m)) if bits==32 else (lambda x,m: 'movq %s, qword ptr %s' % (x,m))
    st = 'movd eax, xmm0\nmov [r12 - %d], rax' if bits==32 else 'movq rax, xmm0\nmov [r12 - %d], rax'
    sign = '0x80000000' if bits==32 else None
    w('\n# ---------------------------------------------------------------- '+t)
    # comparisons
    for n,first,second,cond in [('eq','xmm0','xmm1','eq'),('ne','xmm0','xmm1','ne'),('lt','xmm1','xmm0','a'),('gt','xmm0','xmm1','a'),('le','xmm1','xmm0','ae'),('ge','xmm0','xmm1','ae')]:
        body = ld('xmm0','[r12 - 16]')+'\n'+ld('xmm1','[r12 - 8]')+'\nxor eax, eax\nxor ecx, ecx\nucomi%s %s, %s\n' % (s, first, second)
        if cond=='eq': body += 'sete al\nsetae cl\nand eax, ecx\n'
        elif cond=='ne': body += 'setne al\nsetb cl\nor eax, ecx\n'
        else: body += 'set%s al\n' % cond
        body += 'mov [r12 - 16], rax\nsub r12, 8'
        h('%s_%s' % (t,n), body)
    if bits==32:
        h('f32_abs','mov eax, [r12 - 8]\nand eax, 0x7fffffff\nmov [r12 - 8], rax')
        h('f32_neg','mov eax, [r12 - 8]\nxor eax, 0x80000000\nmov [r12 - 8], rax')
        h('f32_copysign','''mov eax, [r12 - 16]
and eax, 0x7fffffff
mov ecx, [r12 - 8]
and ecx, 0x80000000
or eax, ecx
mov [r12 - 16], rax
sub r12, 8''')
    else:
        h('f64_abs','mov rax, [r12 - 8]\nbtr rax, 63\nmov [r12 - 8], rax')
        h('f64_neg','mov rax, [r12 - 8]\nbtc rax, 63\nmov [r12 - 8], rax'.replace('btc rax, 63','mov rcx, 0x8000000000000000\nxor rax, rcx'))
        h('f64_copysign','''mov rax, [r12 - 16]
btr rax, 63
mov rcx, [r12 - 8]
shr rcx, 63
shl rcx, 63
or rax, rcx
mov [r12 - 16], rax
sub r12, 8''')
    for n,mode in [('ceil',2),('floor',1),('trunc',3),('nearest',0)]:
        h('%s_%s' % (t,n), ld('xmm0','[r12 - 8]')+'\nround%s xmm0, xmm0, %d\n' % (s,mode) + st % 8)
    h(t+'_sqrt', ld('xmm0','[r12 - 8]')+'\nsqrt%s xmm0, xmm0\n' % s + st % 8)
    for n in ['add','sub','mul','div']:
        h('%s_%s' % (t,n), ld('xmm0','[r12 - 16]')+'\n'+ld('xmm1','[r12 - 8]')+'\n%s%s xmm0, xmm1\n' % (n,s) + st % 16 + '\nsub r12, 8')
    # min and max: a NaN operand gives a NaN (quieted); equal operands (+0 and -0) combine their
    # bits, so min prefers -0 and max +0
    if bits==32:
        regs=('eax','ecx','edx'); absmask='0x7fffffff'; inf='0x7f800000'; quiet='0x400000'
        load='mov eax, [r12 - 16]\nmov ecx, [r12 - 8]'
        mv='movd xmm0, eax\nmovd xmm1, ecx'
        store='mov eax, eax\nmov [r12 - 16], rax\nsub r12, 8'
        nan_a='mov edx, eax\nand edx, 0x7fffffff\ncmp edx, 0x7f800000\nja 7f'
        nan_b='mov edx, ecx\nand edx, 0x7fffffff\ncmp edx, 0x7f800000\nja 8f'
        q7='7:  or eax, 0x400000'
        q8='8:  mov eax, ecx\nor eax, 0x400000'
        r='eax'; rb='ecx'
    else:
        load='mov rax, [r12 - 16]\nmov rcx, [r12 - 8]'
        mv='movq xmm0, rax\nmovq xmm1, rcx'
        store='mov [r12 - 16], rax\nsub r12, 8'
        nan_a='mov rdx, rax\nbtr rdx, 63\nmov r8, 0x7ff0000000000000\ncmp rdx, r8\nja 7f'
        nan_b='mov rdx, rcx\nbtr rdx, 63\ncmp rdx, r8\nja 8f'
        q7='7:  bts rax, 51'
        q8='8:  mov rax, rcx\nbts rax, 51'
        r='rax'; rb='rcx'
    for n,comb,pick in [('min','or','jb'),('max','and','ja')]:
        body = load+'\n'+nan_a+'\n'+nan_b+'\n'+mv+'\nucomi%s xmm0, xmm1\njne 2f\n%s %s, %s\njmp 9f\n2:  %s 9f\nmov %s, %s\njmp 9f\n' % (s, comb, r, rb, pick, r, rb)
        body += q7+'\njmp 9f\n'+q8+'\n9:  '+store
        h('%s_%s' % (t,n), body)
